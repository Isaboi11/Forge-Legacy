/*
 * gen-rank-registry.mjs — generate `rank-registry.ts`, the static `assetPath → require()`
 * map for the imported rank badges (Metro needs static literals, so this can't be built at
 * runtime). Keys are the exact paths `resolveRankArtwork` emits, so lookups line up 1:1.
 *
 * Scoped to `assets/artwork/ranks/` only — the Home artwork registry
 * (gen-asset-registry.mjs) deliberately skips this dir so the two stay separate.
 *
 * Run after copying/adding rank art:  node src/domain/rank-artwork/gen-rank-registry.mjs
 */

import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..', '..');
const RANKS = join(REPO, 'assets', 'artwork', 'ranks');

const files = readdirSync(RANKS)
  .filter((f) => f.endsWith('.png'))
  .sort();

const entries = files.map((f) => {
  const rel = `assets/artwork/ranks/${f}`;
  return `  '${rel}': require('@/${rel}'),`;
});

const content = `/**
 * GENERATED by src/domain/rank-artwork/gen-rank-registry.mjs — DO NOT EDIT BY HAND.
 * Static \`assetPath → require()\` map for the imported rank badges (Metro needs static
 * literals). Keys are the exact paths \`resolveRankArtwork\` emits. Regenerate after
 * adding rank art. ${files.length} entries.
 */

export const RANK_ARTWORK_SOURCES: Record<string, number> = {
${entries.join('\n')}
};
`;

writeFileSync(join(HERE, 'rank-registry.ts'), content, 'utf8');
console.log(`wrote rank-registry.ts with ${files.length} entries`);
