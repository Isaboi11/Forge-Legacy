test('0155 adds both enum labels', () => {
  assert.match(M155, /alter type program_state\s+add value if not exists 'finished'/);
  assert.match(M155, /alter type flm_event_type add value if not exists 'PROGRAM_COMPLETED'/);
});

test("⚠ 0155 never USES the labels it adds — that is 55P04 and the whole reason it is a separate file", () => {
  // Everything after `commit;` is commented-out verification, so only the live half is checked.
  const live = M155.slice(0, M155.indexOf('commit;'));
  assert.doesNotMatch(live, /'finished'::/, 'a cast to the new label raises inside the adding transaction');
  assert.doesNotMatch(live, /create (or replace )?function/, 'a function body would parse at creation');
  assert.doesNotMatch(live, /create policy/, 'a policy expression would parse at creation');
});

// ─────────────────────────────────────────────────────────────────────────────
