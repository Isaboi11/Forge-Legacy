/**
 * short-program-migration.test.mjs — 0155/0156 say what they must, and lost nothing on the way.
 *
 * ══ WHY A TEST READS SQL ══
 *
 * These migrations are applied BY HAND in the Supabase SQL editor, so their own `do $$ … $$` self-checks
 * only fire if someone actually runs them. This file asserts the same things at `node --test` time, where
 * they cannot be skipped — the same pattern `notes.test.mjs` established for 0124.
 *
 * The risk being guarded is specific and has happened four times in this schema: rebuilding `save_workout`
 * drops a branch nobody notices until an athlete loses a session. 0156's body was generated by transform
 * rather than typed, and this is the proof that the transform preserved every predecessor's work.
 *
 * Run:  node --test --experimental-strip-types src/domain/program/__tests__/short-program-migration.test.mjs
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const mig = (f) => readFileSync(path.join(here, '../../../../supabase/migrations/', f), 'utf8');

const M155 = mig('0155_program_state_finished.sql');
const M156 = mig('0156_short_program_credit.sql');
const M157 = mig('0157_week_templates.sql');
const M158 = mig('0158_short_program_cap.sql');
const M151 = mig('0151_stair_floors.sql');
