test('⚠ BOTH completion doors are gated — the skip path is the one that gets forgotten', () => {
  const calls = M156.match(/program_earns_credit\(v_prog\.structure\)/g) || [];
  assert.equal(calls.length, 2, 'expected the verdict in save_workout AND skip_program_session');

  const skip = M156.slice(M156.indexOf('create or replace function public.skip_program_session'));
  assert.match(skip, /program_earns_credit/, 'skipping the last session must not graduate a one-week block');
});

test('no unconditional graduation write survives anywhere in 0156', () => {
  assert.doesNotMatch(M156, /set state = 'graduated', ended_at/);
  assert.doesNotMatch(M156, /state = 'graduated', ended_at = now\(\), updated_at = now\(\)\s*\n\s*where/);
});

test('the sealed-state lists all learned the fifth state', () => {
  // start_program's refusal, skip_program_session's refusal, and the structure guard. Miss the guard and
  // a sealed record stays freely restructurable — the one failure here that raises nothing.
  const lists = M156.match(/'graduated', 'finished', 'ended_early'/g) || [];
  assert.ok(lists.length >= 3, `expected >= 3 sealed-state lists, found ${lists.length}`);
  assert.match(M156, /create or replace function public\.programs_guard_structure\(\)/);
});

