/*
 * ⚠ THIS ONE CAUGHT NOTHING AND SHOULD HAVE — added after the fact, 2026-08-13.
 *
 * 0156 shipped to the PO with `as $` where `as $$` belonged, and Postgres refused the whole file with
 * `42601: syntax error at or near "$"`. Every other gate was green: it is a comment-free, type-free,
 * test-free region of a .sql file that nothing in this repo parses.
 *
 * The cause is worth naming because it will happen again to anyone generating SQL from JS:
 * `String.prototype.replace(search, replacement)` treats `$$` IN THE REPLACEMENT STRING as an escape
 * for one literal `$`. Passing a SQL body as that replacement silently halves every `$$` fence in it.
 * `save_workout` survived only because it is fenced with `$fn$`, which has no doubled dollar.
 * (The fix at the source is `replace(token, () => body)` — a replacement function gets no such handling.)
 */
test('⚠ every dollar-quote fence is balanced — a halved `$$` is a file Postgres will not parse', () => {
  for (const [name, src] of [['0155', M155], ['0156', M156], ['0157', M157], ['0158', M158]]) {
    // A `$` that is neither part of `$$` nor part of a `$tag$` fence is always a broken fence here.
    const lone = [...src.matchAll(/(^|[^$A-Za-z_])\$([^$A-Za-z_]|$)/g)];
    assert.equal(lone.length, 0, `${name}: ${lone.length} lone $ — a dollar-quote fence was halved`);

    const tags = {};
    for (const m of src.matchAll(/\$[A-Za-z_]*\$/g)) tags[m[0]] = (tags[m[0]] ?? 0) + 1;
    for (const [tag, n] of Object.entries(tags)) {
      assert.equal(n % 2, 0, `${name}: ${tag} appears ${n} times — fences come in pairs`);
    }
  }
});

