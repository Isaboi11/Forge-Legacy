/*
 * gen-asset-registry.mjs — generate `asset-registry.ts`, the static `assetPath → require()`
 * map the Home hero needs (Metro requires static literals, so this can't be built at runtime).
 * Keys are the exact relative paths the resolver's manifest produces, so lookups line up 1:1.
 *
 * Run after copying/adding artwork:  node src/domain/home-artwork/gen-asset-registry.mjs
 */

import { readdirSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, sep } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..', '..');
const ART = join(REPO, 'assets', 'artwork');

function walk(dir) {
  let out = [];
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out = out.concat(walk(p));
    else if (p.endsWith('.png')) out.push(p);
  }
  return out;
}

const files = walk(ART).sort();
const entries = files.map((f) => {
  const rel = relative(REPO, f).split(sep).join('/'); // e.g. assets/artwork/training-splits/male/full-body.png
  return `  '${rel}': require('@/${rel}'),`;
});

const content = `/**
 * GENERATED by src/domain/home-artwork/gen-asset-registry.mjs — DO NOT EDIT BY HAND.
 * Static \`assetPath → require()\` map for the Home artwork (Metro needs static literals).
 * Keys are the exact paths the resolver manifest emits. Regenerate after adding artwork.
 * ${files.length} entries. Prototype crops — Phase 4 swaps high-res masters.
 */

export const ARTWORK_SOURCES: Record<string, number> = {
${entries.join('\n')}
};
`;

writeFileSync(join(HERE, 'asset-registry.ts'), content, 'utf8');
console.log(`wrote asset-registry.ts with ${files.length} entries`);
