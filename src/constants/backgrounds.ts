/**
 * Screen background artwork — the design's per-screen photographic/textured backgrounds, imported
 * from the handoff. These EXISTED in `design_reference/.../assets/` and were simply never wired
 * (FORGE_DELTAS §16 — a DROPPED-FREE miss, the app rendered a flat gradient instead). Metro needs
 * static `require()` literals. Consumed only via `<ScreenBackground image={SCREEN_BG.x} />`.
 *
 * Palette (from the `.dc` set): `slate` = default standard screens; `slate2` = settings / program /
 * records; `bg2` = create / detail screens; `legacy` = Legacy-family (mountains, the `legacyMountains`
 * layer drives the scroll-fade); `squadDetail` / `squadsHub` = the two squad surfaces.
 *
 * ══ BOTH PALETTES ARE ENUMERATED, AND THAT IS NOT AVOIDABLE ══
 *
 * Metro resolves `require()` from a STRING LITERAL at build time — it cannot take a variable, so the
 * theme cannot be interpolated into the path. Both sets are written out and the choice is made here,
 * once, on the resolved module. The 205 `<ScreenBackground>` call sites are untouched: they ask for
 * `SCREEN_BG.slate` and get whichever plate the active theme means by that.
 *
 * ⚠ THIS DOUBLES THE PLATES IN THE BUNDLE — `assets/backgrounds/` goes from 24 MB to 45 MB, and both
 *   sets ship to every athlete regardless of which theme they use. That is the price of a build-time
 *   `require` and it is worth stating plainly rather than discovering in a bundle report. If it needs
 *   to come down, the lever is downscaling the plates (they are 853×1844 for a 404pt-wide screen), not
 *   dropping a theme.
 *
 * The Paper plates are generated by `scripts/paper-plates/recolor.py` — a reproducible transform, not
 * hand-exported binaries. See that file for the mapping and for why `hero-mountains` takes the
 * opposite one.
 */

