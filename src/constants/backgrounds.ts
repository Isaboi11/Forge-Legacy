/**
 * Screen-level bronze radial-glows, verbatim from each `.dc`'s `radial-gradient(rx ry at cx cy,
 * color 0%, transparent stop)` (FORGE_DELTAS §16). Peaks sit off-screen so only the falloff frames the
 * top/bottom edge. Consumed via `<ScreenBackground radials={[BG_RADIAL.x]} />`.
 *
 * ⚠ THE PAPER ALPHAS ARE HIGHER, NOT LOWER, and that is the opposite of the instinct. A 5% bronze wash
 *   is visible against near-black and invisible against cream — there is simply less room between
 *   `#F4F0E6` and a warm bronze than between `#050505` and one. The hues are the same; only the
 *   strength moves, so the framing these give the screen survives the theme.
 */
