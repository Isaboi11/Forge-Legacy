/** The signatures §4 of the migration closes, in its order. */
export function closedSignatures(migration = read(MIGRATION)) {
  const s4 = migration.slice(migration.indexOf('-- 4. THE DEFINER-REVOKE HALF'), migration.indexOf('-- 5. GRANTS'));
  const lists = arrayLiterals(s4.replace(/--[^\n]*/g, ' '));
  if (lists.length !== 1) throw new Error(`expected one array in §4, found ${lists.length}`);
  return lists[0];
}

