function s2(sigs) {
  return `

-- ═══════════════════════════════════════════════════════════════════════════════════════════════════════
-- §2 — THE ASSERTION (raises if §1 did not land)
-- ═══════════════════════════════════════════════════════════════════════════════════════════════════════

do $$
declare
  r   text;
  bad text;
begin
  foreach r in array array['ai_deploy_log', 'ai_drift_checks'] loop
    if to_regclass('public.' || r) is null then
      raise exception '0271 §2: table public.% is missing', r;
    end if;
    if not (select c.relrowsecurity from pg_class c where c.oid = ('public.' || r)::regclass) then
      raise exception '0271 §2: row-level security is OFF on public.%', r;
    end if;
    if exists (select 1 from pg_policies p where p.schemaname = 'public' and p.tablename = r) then
      raise exception '0271 §2: public.% has a policy — it must have none (server only)', r;
    end if;
  end loop;

  select string_agg(x.role || ' on ' || x.t, ', ') into bad
    from (select r.role, t.t from unnest(array['anon', 'authenticated', 'service_role']) as r(role)
          cross join unnest(array['public.ai_deploy_log', 'public.ai_drift_checks']) as t(t)) x
   where has_table_privilege(x.role, x.t, 'select,insert,update,delete');
  if bad is not null then
    raise exception '0271 §2: a client role holds a table privilege: %', bad;
  end if;

  foreach r in array array['public.ai_deploy_record(text, integer, text, text, text, text, text, text)', 'public.ai_drift_record(jsonb)'] loop
    if to_regprocedure(r) is null then
      raise exception '0271 §2: function % is missing', r;
    end if;
    if has_function_privilege('anon', r, 'execute') or has_function_privilege('authenticated', r, 'execute')
       or has_function_privilege('service_role', r, 'execute') then
      raise exception '0271 §2: % is callable by a client role — it must be postgres only', r;
    end if;
  end loop;

  if to_regprocedure('public.admin_ai_deploys(integer)') is null then
    raise exception '0271 §2: public.admin_ai_deploys(integer) is missing';
  end if;
  if has_function_privilege('anon', 'public.admin_ai_deploys(integer)', 'execute') then
    raise exception '0271 §2: anon can call admin_ai_deploys';
  end if;
  if not has_function_privilege('authenticated', 'public.admin_ai_deploys(integer)', 'execute') then
    raise exception '0271 §2: authenticated cannot call admin_ai_deploys (the page would fail)';
  end if;

  select string_agg(l.f, ', ') into bad
    from (values
${valuesList(sigs)}
    ) as l(f)
   where to_regprocedure(l.f) is not null and has_function_privilege('anon', l.f, 'execute');
  if bad is not null then
    raise exception '0271 §2: still anon-callable after §4: %', bad;
  end if;
end $$;
`;
}

function s3(sigs) {
  return `

-- ═══════════════════════════════════════════════════════════════════════════════════════════════════════
-- §3 — THE REPORT (read-only)
-- ═══════════════════════════════════════════════════════════════════════════════════════════════════════

with l(f) as (
  values
${valuesList(sigs)}
),
present as (select l.f from l where to_regprocedure(l.f) is not null),
definers as (
  select p.oid, p.proname::text as name, pg_get_function_result(p.oid) in ('trigger', 'event_trigger') as is_trigger
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prosecdef and p.prokind = 'f'
     and has_function_privilege('anon', p.oid, 'execute')
)
select
  (select string_agg(c.relname || '=' || c.relrowsecurity, ', ' order by c.relname)
     from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relname in ('ai_deploy_log', 'ai_drift_checks'))                as rls_on,
  (select count(*) from pg_policies p
    where p.schemaname = 'public' and p.tablename in ('ai_deploy_log', 'ai_drift_checks'))           as policies,
  (select count(*) from public.ai_deploy_log)                                                        as deploy_rows,
  (select count(*) from public.ai_drift_checks)                                                      as drift_rows,
  coalesce((select string_agg(x.role || ' ' || x.t, ', ')
     from (select r.role, t.t from unnest(array['anon', 'authenticated', 'service_role']) as r(role)
           cross join unnest(array['public.ai_deploy_log', 'public.ai_drift_checks']) as t(t)) x
    where has_table_privilege(x.role, x.t, 'select,insert,update,delete')), '(none)')               as client_table_grants,
  coalesce((select string_agg(distinct r.role, ', ')
     from unnest(array['anon', 'authenticated', 'service_role']) as r(role)
    where has_function_privilege(r.role, 'public.ai_deploy_record(text, integer, text, text, text, text, text, text)', 'execute')
       or has_function_privilege(r.role, 'public.ai_drift_record(jsonb)', 'execute')), '(none)')       as writers_callable_by,
  coalesce((select string_agg(r.role, ', ')
     from unnest(array['anon', 'authenticated', 'service_role']) as r(role)
    where has_function_privilege(r.role, 'public.admin_ai_deploys(integer)', 'execute')), '(none)')    as reader_callable_by,
  (select count(*) from present p where not has_function_privilege('anon', p.f, 'execute'))
    || ' of ' || (select count(*) from l)                                                            as closed_by_0271,
  (select count(*) from present p where not has_function_privilege('authenticated', p.f, 'execute')) as authenticated_lost,
  coalesce((select string_agg(p.f, ', ') from present p where has_function_privilege('anon', p.f, 'execute')), '(none)')
                                                                                                     as still_anon_in_list,
  coalesce((select string_agg(distinct d.name, ', ' order by d.name) from definers d where not d.is_trigger), '(none)')
                                                                                                     as anon_callable_definers,
  (select count(*) from definers d where d.is_trigger)                                               as anon_callable_trigger_fns,
  now()                                                                                              as checked_at;
`;
}

/** The paste copy, as a string. */
export function buildPending0271() {
  const mig = read(MIGRATION);
  const start = mig.lastIndexOf('\n-- ─', mig.indexOf('-- 0. admin_guard FIRST')) + 1;
  const body = mig.slice(start).trimEnd();
  const sigs = closedSignatures(mig);
  return HEADER + body + '\n' + s2(sigs) + s3(sigs);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(ROOT, PENDING), buildPending0271());
  console.log(`wrote ${PENDING} (${closedSignatures().length} signatures in §2/§3)`);
}
