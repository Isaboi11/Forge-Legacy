function convert(name) {
  let s = readFileSync(`${DIR}/${name}.svg`, 'utf8');
  s = s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  s = s.replace(/<defs>[\s\S]*?<\/defs>/g, '');
  s = s.replace(/<g stroke="url\(#[^)]+\)" stroke-width="1\.35">/g, '<g>');
  s = s.replace(/<g stroke="url\(#[^)]+\)" stroke-width="\.7" opacity="\.85">/g, '<g stroke-width="__FINE__" opacity=".85">');
  s = s.replace(/ fill="url\(#[^)]+\)"/g, ' fill="__FILL__"');
  if (/url\(#/.test(s)) throw new Error(`${name}: a gradient reference survived`);
  if (!s.includes('__FINE__') && !s.includes('<g>')) throw new Error(`${name}: unexpected structure`);
  return s.trim();
}

