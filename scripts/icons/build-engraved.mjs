// Regenerates src/components/forge/primitives/icons/engraved-glyphs.ts from the PO's engraved set.
// Source of truth: design_reference/Forge Modal Library Design/forge-engraved-icons-svg/svg/*.svg
// Each file's <defs> gradient is dropped and its `url(#egNNN)` becomes `url(#G)`; EngravedIcon puts
// its own gradient (per-instance id, per-theme stops) back in at render time.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SRC = 'design_reference/Forge Modal Library Design/forge-engraved-icons-svg/svg'
const OUT = 'src/components/forge/primitives/icons/engraved-glyphs.ts'

const names = readdirSync(SRC).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort()
// Derived glyphs — the set ships one direction only; these are exact mirrors, not redrawings.
const MIRRORS = { 'arrow-left': 'arrow-right' }

const bodies = {}
for (const n of names) {
  const svg = readFileSync(join(SRC, `${n}.svg`), 'utf8')
  const body = svg.replace(/^[\s\S]*<\/defs>/, '').replace(/<\/svg>\s*$/, '').replace(/url\(#eg\d+\)/g, 'url(#G)')
  if (body.includes('<defs') || body.includes('#eg')) throw new Error(`${n}: unexpected markup left`)
  bodies[n] = body
}
for (const [n, from] of Object.entries(MIRRORS)) bodies[n] = `<g transform="translate(24 0) scale(-1 1)">${bodies[from]}</g>`
const all = Object.keys(bodies).sort()
const lines = all.map((n) => `  '${n}': ${JSON.stringify(bodies[n])},`)

writeFileSync(OUT, `// GENERATED by scripts/icons/build-engraved.mjs — do not hand-edit. Re-run the script instead.
// ${names.length} engraved glyphs (+ ${Object.keys(MIRRORS).length} mirrored); the inner markup of each 24×24 SVG, gradient refs as \`url(#G)\`.

export const ENGRAVED_GLYPHS = {
${lines.join('\n')}
} as const

export type EngravedName = keyof typeof ENGRAVED_GLYPHS
`)
console.log(`${names.length} glyphs → ${OUT}`)
