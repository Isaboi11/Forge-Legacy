// Regenerates site/assets/forge-engraved.js — the landing site's copy of the PO's engraved icon set.
// Same source and same body rewrite as build-engraved.mjs (the app's copy); re-run both after an icon changes.
// Source of truth: design_reference/Forge Modal Library Design/forge-engraved-icons-svg/svg/*.svg
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SRC = 'design_reference/Forge Modal Library Design/forge-engraved-icons-svg/svg'
const OUT = 'site/assets/forge-engraved.js'

const names = readdirSync(SRC).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort()
const MIRRORS = { 'arrow-left': 'arrow-right' }

const bodies = {}
for (const n of names) {
  const svg = readFileSync(join(SRC, `${n}.svg`), 'utf8')
  const body = svg.replace(/^[\s\S]*<\/defs>/, '').replace(/<\/svg>\s*$/, '').replace(/url\(#eg\d+\)/g, 'url(#G)')
  if (body.includes('<defs') || body.includes('#eg')) throw new Error(`${n}: unexpected markup left`)
  bodies[n] = body
}
for (const [n, from] of Object.entries(MIRRORS)) bodies[n] = `<g transform="translate(24 0) scale(-1 1)">${bodies[from]}</g>`
const all = Object.keys(bodies).sort()

writeFileSync(OUT, `/* GENERATED by scripts/icons/build-engraved-site.mjs — do not hand-edit. Re-run the script instead.
 *
 * Forge Legacy — the engraved icon set (PO, 2026-09-25), ${all.length} glyphs. The site's twin of the app's EngravedIcon.
 *
 *   ForgeEngraved.svg('trophy', { size: 20 })                 -> string, bronze gradient
 *   ForgeEngraved.svg('check', { size: 18, color: 'currentColor' }) -> string, one flat colour
 *   ForgeEngraved.create(React, 'barbell', { size: 16, tone: 'forge' }) -> React element
 *
 * Tone rule (same as the app): symbols that MEAN something wear the gradient; small controls and
 * state colours stay flat via \`color\`. \`tone\` picks the stops: 'forge' (dark screens, the default inside
 * the phone mock-ups) or 'paper' (the site's cream pages — Alabaster's darker stops, so the top of the
 * glyph doesn't vanish on a light ground). Every instance gets its own gradient id.
 */
(function (root) {
  var G = {
${all.map((n) => `    '${n}': ${JSON.stringify(bodies[n])},`).join('\n')}
  };
  var STOPS = { forge: ['#F3D9AE', '#C99767', '#7E5C3B'], paper: ['#A47A3D', '#8C6B3C', '#5C4726'] };
  var n = 0;
  function svg(name, o) {
    o = o || {};
    var body = G[name];
    if (!body) return '';
    var size = o.size || 24, scale = Math.max(1, (1.2 * 24) / size / 1.35);
    if (scale > 1) body = body.replace(/stroke-width="([\\d.]+)"/g, function (_, w) { return 'stroke-width="' + (parseFloat(w) * scale).toFixed(2) + '"'; });
    var defs = '';
    if (o.color) body = body.replace(/url\\(#G\\)/g, o.color);
    else {
      var id = 'feg' + (++n), s = STOPS[o.tone] || STOPS.forge;
      body = body.replace(/url\\(#G\\)/g, 'url(#' + id + ')');
      defs = '<defs><linearGradient id="' + id + '" gradientUnits="userSpaceOnUse" x1="0" y1="2" x2="0" y2="22"><stop offset="0" stop-color="' + s[0] + '"/><stop offset=".5" stop-color="' + s[1] + '"/><stop offset="1" stop-color="' + s[2] + '"/></linearGradient></defs>';
    }
    return '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" stroke-linecap="round" stroke-linejoin="round" style="display:block;flex:none">' + defs + body + '</svg>';
  }
  function create(React, name, o) {
    var html = svg(name, o);
    if (!html) return null;
    return React.createElement('span', { 'aria-hidden': 'true', style: { display: 'inline-flex', flex: 'none', lineHeight: 0 }, dangerouslySetInnerHTML: { __html: html } });
  }
  var api = { svg: svg, create: create, names: Object.keys(G) };
  root.ForgeEngraved = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
`)
console.log(`${all.length} glyphs → ${OUT}`)
