/**
 * Generate `src/domain/coach/author-catalogue.ts` — the exercises the app shows, for coach-author's prompt.
 *
 *   node --experimental-strip-types scripts/build-author-catalogue.mjs
 *
 * Holt writes a typed workout himself (Coach-AI-Amendment-003), and he may only write movements the app can
 * open, log and swap. So the prompt carries the VISIBLE catalogue — `buildPickerDb`, the same source the
 * Exercise Picker renders — never `exercises.json`, which holds rows the app withholds. Grouped by movement
 * pattern; each line is `equipment|primary muscles: key key key`, with `*` after a hold and `^` after an
 * advanced movement. The module has no imports so the function can inline it; `author.test.mjs` fails if it drifts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'src/domain/coach/author-catalogue.ts';

const source = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'src/domain/exercise-relationships/source', f), 'utf8'));

export async function authorCatalogueSource() {
  const { buildPickerDb } = await import(pathToFileURL(path.join(ROOT, 'src/domain/exercise-picker/catalog-core.ts')).href);
  const pool = buildPickerDb({
    exercises: source('exercises.json'),
    exerciseMuscles: source('exercise_muscles.json'),
    muscles: source('muscles.json'),
    equipment: source('equipment.json'),
  });

  /* Grouped twice — by pattern, then by equipment and primary muscles — so neither is repeated on every
     movement: the list is ~11k tokens line-per-row and about half that this way, and the dashboard paste
     copy stays under the size the editor once truncated at (compact-deploy.mjs). */
  const byPattern = new Map();
  for (const ex of [...pool].sort((x, y) => x.key.localeCompare(y.key))) {
    const groups = byPattern.get(ex.pattern) ?? new Map();
    const head = ex.equipId + '|' + ex.primaryMuscleIds.join(',');
    const mark = (ex.unit === 'time' ? '*' : '') + (ex.difficulty === 'Advanced' ? '^' : '');
    groups.set(head, [...(groups.get(head) ?? []), ex.key + mark]);
    byPattern.set(ex.pattern, groups);
  }
  const text = [...byPattern.keys()]
    .sort()
    .map((p) => `## ${p}\n${[...byPattern.get(p).keys()].sort().map((h) => `${h}: ${byPattern.get(p).get(h).join(' ')}`).join('\n')}`)
    .join('\n\n');

  return `/**
 * GENERATED by scripts/build-author-catalogue.mjs from the visible exercise catalogue — do not edit. Grouped by
 * movement pattern; each line is \`equipment|primary muscles: key key key\`, \`*\` after a hold, \`^\` after advanced.
 * No imports: coach-author inlines this file.
 */
export const AUTHOR_CATALOGUE_COUNT = ${pool.length};
export const AUTHOR_CATALOGUE = ${JSON.stringify(text)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(ROOT, OUT), await authorCatalogueSource());
  console.log(`wrote ${OUT}`);
}
