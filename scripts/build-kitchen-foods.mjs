/**
 * Generate `src/domain/nutrition/kitchen-foods.ts` — the catalogue's food names, for coach-kitchen's prompt.
 *
 *   node --experimental-strip-types scripts/build-kitchen-foods.mjs
 *
 * Live check 2026-09-26: 272 of 457 ingredient lines Holt wrote didn't match the catalogue ("rice", "oil",
 * "1 can black beans"), so dish cards showed "≈30 cal" for a beef skillet. Holt now writes `food` as one of
 * these names when one fits — the name BEFORE the comma, as `recipe-import.ts` `matchFood` compares — and the
 * amount by weight, which `gramsFor` always converts. The module has no imports so the function can inline it;
 * `kitchen-dishes.test.mjs` fails if it drifts from `recipes-data.ts`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'src/domain/nutrition/kitchen-foods.ts';

export async function kitchenFoodsSource() {
  const { INGREDIENTS } = await import(pathToFileURL(path.join(ROOT, 'src/domain/nutrition/recipes-data.ts')).href);
  const heads = [...new Set(Object.values(INGREDIENTS).map((i) => i.name.split(',')[0].replace(/\([^)]*\)/g, '').replace(/\s+/g, ' ').trim().toLowerCase()))].sort();
  return `/**
 * GENERATED by scripts/build-kitchen-foods.mjs from recipes-data.ts — do not edit. The catalogue's food names
 * (before the comma), which coach-kitchen asks Holt to use so every line matches (\`matchFood\`). No imports:
 * the function inlines this file.
 */
export const KITCHEN_FOODS = ${JSON.stringify(heads.join('; '))};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(ROOT, OUT), await kitchenFoodsSource());
  console.log(`wrote ${OUT}`);
}
